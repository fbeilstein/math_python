class TestLevel1Axioms(unittest.TestCase):
    def test_z4_passes(self):
        table = [[0,1,2,3],[1,2,3,0],[2,3,0,1],[3,0,1,2]]
        self.assertTrue(tasks.check_closure(table))
        self.assertTrue(tasks.check_associativity(table))
        self.assertEqual(tasks.find_identity(table), 0)
        self.assertTrue(tasks.check_inverses(table, 0))

    def test_broken_table_closure(self):
        table = [[0,1],[1,5]]  # 5 is not in {0,1}
        self.assertFalse(tasks.check_closure(table))

    def test_z6_mul_no_inverses(self):
        table = [[(i*j)%6 for j in range(6)] for i in range(6)]
        self.assertEqual(tasks.find_identity(table), 1)
        self.assertFalse(tasks.check_inverses(table, 1))  # 2, 3, 4 have no inverses


class TestLevel2Permutations(unittest.TestCase):
    def test_compose(self):
        p = [1, 2, 0]  # (0 1 2)
        q = [1, 0, 2]  # (0 1)
        r = tasks.compose_permutations(p, q)
        self.assertEqual(r, [2, 1, 0])  # p(q(i)): 0→1→2, 1→0→1, 2→2→0

    def test_inverse(self):
        p = [1, 2, 0]
        inv = tasks.inverse_permutation(p)
        identity = tasks.compose_permutations(p, inv)
        self.assertEqual(identity, [0, 1, 2])

    def test_order(self):
        p = [1, 2, 0]  # 3-cycle, order 3
        self.assertEqual(tasks.permutation_order(p), 3)
        self.assertEqual(tasks.permutation_order([0, 1, 2]), 1)

    def test_cycle_conversion(self):
        p = [1, 2, 0, 4, 3]
        cycles = tasks.one_line_to_cycles(p)
        self.assertEqual(len(cycles), 2)
        back = tasks.cycles_to_one_line(cycles, 5)
        self.assertEqual(back, p)

    def test_generate_group_cyclic(self):
        gens = [[1, 2, 0]]  # (0 1 2), generates Z3
        group = tasks.generate_permutation_group(gens, 3)
        self.assertEqual(len(group), 3)

    def test_generate_group_s3(self):
        gens = [[1, 2, 0], [1, 0, 2]]  # (0 1 2), (0 1) generate S3
        group = tasks.generate_permutation_group(gens, 3)
        self.assertEqual(len(group), 6)

    def test_parity(self):
        self.assertTrue(tasks.is_even_permutation([0, 1, 2]))  # identity
        self.assertFalse(tasks.is_even_permutation([1, 0, 2]))  # transposition
        self.assertTrue(tasks.is_even_permutation([1, 2, 0]))   # 3-cycle

