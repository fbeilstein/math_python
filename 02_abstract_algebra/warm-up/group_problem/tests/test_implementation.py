class TestLevel7Homomorphisms(unittest.TestCase):
    def test_z6_to_z3(self):
        G = ge.from_Zn(6)
        H = ge.from_Zn(3)
        phi = [i % 3 for i in range(6)]
        self.assertTrue(tasks.is_homomorphism(G, H, phi))
        ker = tasks.compute_kernel(G, H, phi)
        self.assertEqual(len(ker), 2)  # {0, 3}
        img = tasks.compute_image(G, H, phi)
        self.assertEqual(len(img), 3)  # all of Z3

    def test_bad_homomorphism(self):
        G = ge.from_Zn(4)
        H = ge.from_Zn(3)
        phi = [0, 1, 2, 0]  # not a homomorphism
        self.assertFalse(tasks.is_homomorphism(G, H, phi))


class TestGroupEngine(unittest.TestCase):
    def test_zn(self):
        G = ge.from_Zn(5)
        self.assertEqual(G.order, 5)
        self.assertEqual(G.multiply(2, 3), 0)
        self.assertEqual(G.inverse(2), 3)

    def test_un(self):
        G = ge.from_Un(8)
        self.assertEqual(G.order, 4)  # {1, 3, 5, 7}

    def test_dn(self):
        G = ge.from_Dn(3)
        self.assertEqual(G.order, 6)

    def test_sn(self):
        G = ge.from_Sn(3)
        self.assertEqual(G.order, 6)

    def test_from_perms(self):
        # S3 from generators (0 1 2) and (0 1)
        gens = [(1, 2, 0), (1, 0, 2)]
        G = ge.from_permutation_generators(gens, 3)
        self.assertEqual(G.order, 6)

    def test_element_order(self):
        G = ge.from_Zn(6)
        self.assertEqual(G.element_order(0), 1)  # identity
        self.assertEqual(G.element_order(1), 6)  # generator
        self.assertEqual(G.element_order(2), 3)
        self.assertEqual(G.element_order(3), 2)


